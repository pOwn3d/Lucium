// The page guard of the iOS application: the code that runs in a page before its own scripts, and the rules of our own it is given (docs/ios.md,
// section 6.4). Nothing here is a list of someone else's and nothing is downloaded: the code is the Mac's (src/preload/guard-world.ts, the
// scriptlet library of src/shared/scriptlets.ts), the YouTube rules are the Mac's (src/shared/youtube-rules.ts), the consent walls are the Mac's
// (`consentWallCss`). This file only puts them in the two files the application embeds:
//
//   guard-runtime.js   an expression `(function (plan) { … })`; the application appends `(<plan as JSON>)` and hands the text to WebKit as a user script
//   guard-rules.json   what the application needs of our own rules: the YouTube scriptlets, the style sheets, and the rules WebKit reads
//
// The runtime takes a plan `{ scriptlets: [{ id, args }], css: string }`: the application decides, for each page, what goes in it
// (LuciumKit's PagePlanner), and the page-side library checks every call again before it runs one.
//
// Pure: text in, files out. Loaded by Node with type stripping: no enum, no parameter property.

/** A scriptlet call as the Mac's library names it. */
export interface Call {
  id: string
  args: readonly string[]
}

export interface GuardInputs {
  /** The text of `guardWorld` (src/preload/guard-world.ts), a self-contained function: `guardWorld.toString()`. */
  guardWorldSource: string
  /** The site of the YouTube rules, the calls for its pages, the style sheet that hides its ad blocks, and the paths of it that serve advertising. */
  youtube: { domain: string; scriptlets: readonly Call[]; css: string; adPaths: readonly string[] }
  /** The style sheet of the consent walls (`consentWallCss()`): hides the known containers and gives the scrolling back. */
  consentWallCss: string
  /** The Mac's check of a call (`parseScriptletCall`): one that it refuses is never written. */
  parse: (name: unknown, args: unknown) => { ok: true; call: Call } | { ok: false; reason: { key: string } }
}

/** A rule of the format WebKit reads (`WKContentRuleList`); only the blocks below are written. */
export interface BlockRule {
  trigger: { 'url-filter': string }
  action: { type: 'block' }
}

export interface GuardRules {
  schema: 1
  youtube: {
    domain: string
    /** `[id, args]`, as in the scriptlet tables of the lists. */
    scriptlets: Array<[string, string[]]>
    css: string
    /** The requests of youtube.com that serve advertising, as rules for WebKit. */
    networkRules: BlockRule[]
  }
  consentWalls: { css: string }
}

export const RUNTIME_FILE = 'guard-runtime.js'
export const RULES_FILE = 'guard-rules.json'

/** The text of a regular expression that matches `literal` and nothing else. */
const escapeRegex = (literal: string): string => literal.replace(/[.+?(){}[\]|\\$^*]/g, '\\$&')

/** The rule that blocks one path of a site (and of its subdomains): the same reading as `||site/path` in a list. No alternation: WebKit refuses it. */
export function blockPath(domain: string, path: string): BlockRule {
  return { trigger: { 'url-filter': `^[a-z]+://([^/]+\\.)?${escapeRegex(domain)}${escapeRegex(path)}` }, action: { type: 'block' } }
}

/** The runtime: `guardWorld` and the little that puts a style sheet in. It runs in the page's own world, before the page's scripts. */
export function guardRuntime(guardWorldSource: string): string {
  if (!/^(async\s+)?function\s+guardWorld\s*\(/.test(guardWorldSource.trimStart())) throw new Error('guardWorld is not a function declaration: its text cannot be embedded')
  return `// Generated by scripts/ios-guard.mjs from src/preload/guard-world.ts: do not edit.
(function (plan) {
  'use strict';
  const guardWorld = (${guardWorldSource.trim()});
  const addStyle = (css) => {
    try {
      // A constructed sheet is not blocked by a page's content security policy, as a <style> element can be.
      const sheet = new CSSStyleSheet();
      sheet.replaceSync(css);
      document.adoptedStyleSheets = [...document.adoptedStyleSheets, sheet];
    } catch (error) {
      try {
        const style = document.createElement('style');
        style.textContent = css;
        (document.head || document.documentElement).appendChild(style);
      } catch (second) {
        console.debug('[guard] a style sheet could not be added:', second instanceof Error ? second.message : String(second));
      }
    }
  };
  if (typeof plan.css === 'string' && plan.css !== '') addStyle(plan.css);
  if (Array.isArray(plan.scriptlets) && plan.scriptlets.length > 0) guardWorld({ scriptlets: plan.scriptlets, fingerprint: null });
})
`
}

/** The rules of our own. Throws when the Mac's library refuses one of the YouTube calls: a rule that would never run is not shipped. */
export function guardRules(inputs: GuardInputs): GuardRules {
  const scriptlets: Array<[string, string[]]> = []
  for (const call of inputs.youtube.scriptlets) {
    const verdict = inputs.parse(call.id, [...call.args])
    if (!verdict.ok) throw new Error(`the YouTube scriptlet ${call.id} is refused by the library (${verdict.reason.key})`)
    scriptlets.push([verdict.call.id, [...verdict.call.args]])
  }
  return {
    schema: 1,
    youtube: { domain: inputs.youtube.domain, scriptlets, css: inputs.youtube.css, networkRules: inputs.youtube.adPaths.map((path) => blockPath(inputs.youtube.domain, path)) },
    consentWalls: { css: inputs.consentWallCss }
  }
}

/** The files the application embeds, name → content. */
export function guardFiles(inputs: GuardInputs): Record<string, string> {
  return { [RUNTIME_FILE]: guardRuntime(inputs.guardWorldSource), [RULES_FILE]: `${JSON.stringify(guardRules(inputs))}\n` }
}
