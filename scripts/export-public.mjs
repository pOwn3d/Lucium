// Makes the tree of the public repository and prepares its one commit, or only checks that it could be made. The public repository has no
// earlier history: it starts from an export of the commit (`git archive HEAD`, less the paths marked `export-ignore` in .gitattributes).
// Nothing is pushed and no remote is added: the maintainer reads the result, then adds the public remote by hand
// (docs/community/public-repository.md).
//
//   node scripts/export-public.mjs --check [--commit <hash>]
//   node scripts/export-public.mjs --commit <hash> <empty folder>
//
// --check           every control, nothing created (the export goes in a temporary folder that is removed), and the summary
// --commit <hash>   the commit that was read and approved: HEAD must be it. Required for an export
// --message "…"     the message of the commit (by default « chore: Lucium <version>, the first commit of the public repository »)
//
// The export is refused, with the reason of each refusal, when:
//   - the working tree is not clean, or HEAD is not the commit given;
//   - the folder is not empty, or is inside a repository;
//   - the export holds an internal path, a key file, a home folder, a host or a tool of the maintainer, a finding of an unpublished audit,
//     or the former name of the project (the rules of src/main/public-export.ts, the ones the tests apply to the tracked files);
//   - a file that is not under the GPL (the logo, the media generated by AI) is exported without the notice that says its licence, or
//     NOTICE does not name that notice;
//   - the complete secret scan finds something (gitleaks and trufflehog, each one that is installed, unverified findings included), or no
//     scanner is installed, or one fails;
//   - the author or the committer git would write is not a …@users.noreply.github.com address, or commits are not signed;
//   - the export weighs more than the ceiling (MAX_EXPORT_BYTES);
//   - the repository that was made is not exactly one signed commit of that tree on `main`, with no remote.
// A refused export leaves the folder empty.
//
// Exit code: 0 every control passed, 1 refused (each reason is said), 2 the arguments are wrong.
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

process.removeAllListeners('warning')
process.on('warning', (warning) => {
  if (/** @type {NodeJS.ErrnoException} */ (warning).code !== 'MODULE_TYPELESS_PACKAGE_JSON') console.error(`${warning.name}: ${warning.message}`)
})
const { megabytes, runExport, unreadReport, MAX_EXPORT_BYTES } = await import('../src/main/public-export.ts')

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const usage = () => console.error(readFileSync(new URL(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).map((l) => l.slice(3)).join('\n'))

const positional = []
/** @type {{ commit?: string, message?: string }} */
const options = {}
let check = false
const args = process.argv.slice(2)
for (let at = 0; at < args.length; at++) {
  const arg = args[at]
  const named = /^--(commit|message)(?:=(.*))?$/s.exec(arg)
  if (named) {
    const value = named[2] ?? args[++at]
    if (value === undefined) {
      console.error(`${arg} needs a value.\n`)
      usage()
      process.exit(2)
    }
    options[named[1]] = value
  } else if (arg === '--check') check = true
  else if (arg === '--help' || arg === '-h') {
    usage()
    process.exit(0)
  } else if (arg.startsWith('--')) {
    console.error(`Unknown option ${arg}.\n`)
    usage()
    process.exit(2)
  } else positional.push(arg)
}
if (check ? positional.length > 0 : positional.length !== 1 || options.commit === undefined) {
  console.error(check ? '--check takes no folder: it creates nothing.\n' : 'An export needs --commit <hash> and one empty folder.\n')
  usage()
  process.exit(2)
}

const result = runExport({ repo: root, dest: positional[0], expected: options.commit, check, message: options.message })

console.log(`Commit exported   ${result.head || 'unreadable'}${check && options.commit === undefined ? ' (not compared: no --commit given)' : ''}`)
console.log(`Files             ${result.files}`)
console.log(`Size              ${megabytes(result.bytes)} (${result.bytes} bytes; ceiling ${megabytes(MAX_EXPORT_BYTES)})`)
console.log(`Tree              ${result.tree || 'not exported'}`)
for (const line of unreadReport(result.unread)) console.log(line)
if (result.commit) {
  console.log(`Commit prepared   ${result.commit} in ${resolve(positional[0])}, branch main, signed, no remote. Nothing was pushed.`)
  console.log('Read it there (`git show --stat --show-signature`; `git rev-parse HEAD^{tree}` answers the tree above), then go on with the checklist.')
}
if (result.refusals.length > 0) {
  console.error(`\nRefused, ${result.refusals.length} reason(s):`)
  for (const refusal of result.refusals) console.error(`  - ${refusal}`)
  process.exit(1)
}
if (check) console.log('\nEvery control passed. Nothing was created.')
